"""
Evaluation data for Module 9 (PROVIDED — you do not edit this file).

This module is the single source of truth for every word list in the exercise, so
the training data behind the bundled checkpoints and the held-out evaluation cases
can never accidentally overlap. Four tasks:

  uppercase : "uppercase: token"  -> "TOKEN"        (word splits are disjoint)
  repeat    : "repeat: data"      -> "data"         (word splits are disjoint)
  reverse   : "reverse: qmvbz"    -> "zbvmq"        (word splits are disjoint)
  qa        : "color of sky?"     -> "it is blue"   (SEE THE NOTE BELOW)

The `qa` task is deliberately *contaminated*: the eight facts the models memorize
during finetuning are exactly the eight facts the suite tests. Every other task uses
words the model has never seen. That contrast is the point of the contamination
extra credit, and it is why the qa column of the report should be read with
suspicion even when it is the highest number on the page.

Answers are lists, because more than one string can be right ("it is blue" and
"blue"), which is what token-level F1 and multi-answer exact match exist for.
"""

from __future__ import annotations

import json
import random
from pathlib import Path

LETTERS = "abcdefghijklmnopqrstuvwxyz"

# ---------------------------------------------------------------------------
# Word banks. Every character here is in the 65-character Module 5 vocabulary.
# ---------------------------------------------------------------------------

UPPERCASE_TRAIN = [
    "hello", "world", "python", "machine", "learning", "model", "token", "embed",
    "attention", "neuron", "layer", "batch", "train", "loss", "gradient", "vector",
    "matrix", "sample", "logit", "softmax", "encoder", "decoder", "weight", "bias",
    "prompt", "answer", "reason", "reward", "policy", "value",
]
UPPERCASE_EVAL = [
    "metric", "score", "budget", "harness", "report", "signal",
    "context", "window", "corpus", "recall",
]

REPEAT_TRAIN = [
    "cat", "dog", "sun", "moon", "star", "tree", "code", "data", "text", "word",
    "chat", "bot", "run", "fun", "book", "note", "rule", "test", "line", "page",
]
REPEAT_EVAL = ["fact", "gold", "task", "grid", "step", "hint", "list", "seed"]

# A tiny model that only ever saw thirty English words memorizes them instead of
# learning the transformation, and then fails on every held-out word. Padding the
# finetuning set with hundreds of random strings of varying length forces it to
# learn "uppercase each character" and "copy each character" as rules, which is
# what makes a held-out English word a fair test.
N_FILLER = 500
FILLER_MIN_LEN = 4
FILLER_MAX_LEN = 7

QA_FACTS = [
    ("color of sky?", ["it is blue", "blue"]),
    ("color of grass?", ["it is green", "green"]),
    ("capital of france?", ["it is paris", "paris"]),
    ("capital of japan?", ["it is tokyo", "tokyo"]),
    ("capital of germany?", ["it is berlin", "berlin"]),
    ("opposite of hot?", ["it is cold", "cold"]),
    ("opposite of up?", ["it is down", "down"]),
    ("opposite of day?", ["it is night", "night"]),
]

# Reverse uses random five-letter strings so the task cannot be memorized: the
# model has to learn the transformation itself.
WORD_LENGTH = 5
N_REVERSE_SFT = 250      # taught during finetuning (deliberately small: reverse is
                         # left half-learned so the RL stage has room to improve it)
N_REVERSE_RL = 256       # the prompts GRPO trains on
N_REVERSE_EVAL = 24      # held out from both, used only by the evaluation suite


def _unique_words(seed: int, count: int, length: int) -> list[str]:
    """Deterministically draw `count` distinct lowercase strings of a given length."""
    rng = random.Random(seed)
    words: set[str] = set()
    while len(words) < count:
        words.add("".join(rng.choice(LETTERS) for _ in range(length)))
    out = sorted(words)
    rng.shuffle(out)
    return out


def _filler_words(seed: int) -> list[str]:
    """Random strings of varying length, used only to pad the finetuning set."""
    rng = random.Random(seed)
    words: set[str] = set()
    while len(words) < N_FILLER:
        n = rng.randint(FILLER_MIN_LEN, FILLER_MAX_LEN)
        words.add("".join(rng.choice(LETTERS) for _ in range(n)))
    return sorted(words)


def reverse_splits(seed: int = 0) -> dict[str, list[str]]:
    """Return disjoint {'sft', 'rl', 'eval'} reverse-word lists."""
    total = N_REVERSE_SFT + N_REVERSE_RL + N_REVERSE_EVAL
    pool = _unique_words(seed, total, WORD_LENGTH)
    return {
        "sft": pool[:N_REVERSE_SFT],
        "rl": pool[N_REVERSE_SFT:N_REVERSE_SFT + N_REVERSE_RL],
        "eval": pool[N_REVERSE_SFT + N_REVERSE_RL:],
    }


# ---------------------------------------------------------------------------
# Training data (used only by solution/src/make_checkpoints.py)
# ---------------------------------------------------------------------------


def sft_pairs(seed: int = 42) -> list[dict[str, str]]:
    """Prompt-response pairs for the multi-task instruction finetune."""
    rng = random.Random(seed)
    filler = _filler_words(seed + 1)
    pairs: list[dict[str, str]] = []
    for w in UPPERCASE_TRAIN + filler:
        pairs.append({"prompt": f"uppercase: {w}", "response": w.upper()})
    for w in REPEAT_TRAIN + filler:
        pairs.append({"prompt": f"repeat: {w}", "response": w})
    for _ in range(200):
        q, answers = rng.choice(QA_FACTS)
        pairs.append({"prompt": q, "response": answers[0]})
    for w in reverse_splits()["sft"]:
        pairs.append({"prompt": f"reverse: {w}", "response": w[::-1]})
    rng.shuffle(pairs)
    return pairs


def rl_prompts() -> list[dict[str, str]]:
    """The reverse prompts GRPO trains on (disjoint from SFT and from eval)."""
    return [{"prompt": f"reverse: {w}", "answer": w[::-1]} for w in reverse_splits()["rl"]]


# ---------------------------------------------------------------------------
# The evaluation suite itself
# ---------------------------------------------------------------------------


def eval_cases() -> list[dict[str, object]]:
    """Build the held-out benchmark cases, one record per case.

    Each record is {id, task, prompt, answers}. `answers` is the list of strings
    that count as correct, which is what `exact_match` and `token_f1` consume.
    """
    cases: list[dict[str, object]] = []

    for w in UPPERCASE_EVAL:
        cases.append({"task": "uppercase", "prompt": f"uppercase: {w}", "answers": [w.upper()]})
    for w in REPEAT_EVAL:
        cases.append({"task": "repeat", "prompt": f"repeat: {w}", "answers": [w]})
    for w in reverse_splits()["eval"]:
        cases.append({"task": "reverse", "prompt": f"reverse: {w}", "answers": [w[::-1]]})
    for question, answers in QA_FACTS:
        cases.append({"task": "qa", "prompt": question, "answers": list(answers)})

    for i, case in enumerate(cases, start=1):
        case["id"] = f"case-{i:03d}"
    return cases


def multiple_choice_cases() -> list[dict[str, object]]:
    """Four-option questions scored by likelihood, no generation required.

    Wrong options are drawn from the *other* facts and tasks, so a model that has
    learned nothing scores at chance (25%) and a model that has learned the task
    scores well above it.
    """
    rows: list[tuple[str, list[str], int]] = [
        ("color of sky?", ["it is blue", "it is green", "it is cold", "it is paris"], 0),
        ("color of grass?", ["it is blue", "it is green", "it is night", "it is tokyo"], 1),
        ("capital of france?", ["it is berlin", "it is tokyo", "it is paris", "it is down"], 2),
        ("capital of japan?", ["it is paris", "it is tokyo", "it is berlin", "it is blue"], 1),
        ("capital of germany?", ["it is berlin", "it is paris", "it is green", "it is cold"], 0),
        ("opposite of hot?", ["it is night", "it is down", "it is cold", "it is blue"], 2),
        ("opposite of up?", ["it is down", "it is cold", "it is berlin", "it is green"], 0),
        ("opposite of day?", ["it is night", "it is blue", "it is tokyo", "it is down"], 0),
        ("uppercase: metric", ["METRIC", "metric", "MERTIC", "CIRTEM"], 0),
        ("uppercase: score", ["SCORE", "SOCRE", "score", "EROCS"], 0),
        ("repeat: fact", ["fact", "FACT", "tcaf", "fatc"], 0),
        ("repeat: gold", ["gold", "dlog", "GOLD", "golg"], 0),
    ]
    reverse_eval = reverse_splits()["eval"]
    for w in reverse_eval[:4]:
        correct = w[::-1]
        distractors = [w, correct[1:] + correct[0], correct[::-1][1:] + "z"]
        rows.append((f"reverse: {w}", [correct] + distractors, 0))

    out: list[dict[str, object]] = []
    for i, (question, options, answer_index) in enumerate(rows, start=1):
        out.append({
            "id": f"mc-{i:03d}",
            "question": question,
            "options": options,
            "answer_index": answer_index,
        })
    return out


# ---------------------------------------------------------------------------
# JSONL helpers
# ---------------------------------------------------------------------------


def save_jsonl(records: list[dict], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        for item in records:
            f.write(json.dumps(item) + "\n")


def load_jsonl(path: Path) -> list[dict]:
    out = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                out.append(json.loads(line))
    return out


if __name__ == "__main__":
    # Regenerate the bundled evaluation files.
    data_dir = Path(__file__).resolve().parent.parent / "data"
    save_jsonl(eval_cases(), data_dir / "tasks.jsonl")
    save_jsonl(multiple_choice_cases(), data_dir / "multiple_choice.jsonl")
    print(f"Wrote {data_dir / 'tasks.jsonl'} ({len(eval_cases())} cases)")
    print(f"Wrote {data_dir / 'multiple_choice.jsonl'} ({len(multiple_choice_cases())} questions)")
