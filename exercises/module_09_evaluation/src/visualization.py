"""
Module 9 plotting (PROVIDED — you do not edit this file).

One figure: a grouped bar chart of per-task exact-match accuracy for the two
checkpoints, with the suite average drawn beside it. The picture is the argument
&mdash; the two averages are close, and the per-task bars are not. Matplotlib uses
the non-interactive Agg backend so it runs headless on a laptop.
"""

from __future__ import annotations

from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

INSTRUCT_COLOR = "#1f6feb"
RL_COLOR = "#d29922"


def save_task_comparison(
    tasks: list[str],
    instruct_scores: list[float],
    rl_scores: list[float],
    out_path: str | Path,
    instruct_overall: float | None = None,
    rl_overall: float | None = None,
) -> None:
    """Grouped bar chart of per-task accuracy for both models."""
    labels = list(tasks)
    left = list(instruct_scores)
    right = list(rl_scores)
    if instruct_overall is not None and rl_overall is not None:
        labels = labels + ["suite avg"]
        left = left + [instruct_overall]
        right = right + [rl_overall]

    positions = range(len(labels))
    width = 0.38

    fig, ax = plt.subplots(figsize=(8, 4.5), dpi=120)
    bars_a = ax.bar([p - width / 2 for p in positions], left, width,
                    color=INSTRUCT_COLOR, label="instruct (Module 6)")
    bars_b = ax.bar([p + width / 2 for p in positions], right, width,
                    color=RL_COLOR, label="RL / GRPO (Module 7)")

    for bars in (bars_a, bars_b):
        for bar in bars:
            ax.text(bar.get_x() + bar.get_width() / 2, bar.get_height() + 0.02,
                    f"{bar.get_height():.0%}", ha="center", va="bottom", fontsize=8)

    if instruct_overall is not None:
        ax.axvline(len(labels) - 1.5, color="#888888", linewidth=1, linestyle=":")

    ax.set_xticks(list(positions))
    ax.set_xticklabels(labels)
    ax.set_ylabel("exact-match accuracy (greedy)")
    ax.set_ylim(0, 1.12)
    ax.set_yticks([0.0, 0.25, 0.5, 0.75, 1.0])
    ax.set_yticklabels(["0%", "25%", "50%", "75%", "100%"])
    ax.set_title("Per-task accuracy: RL wins the task it trained on")
    ax.grid(True, axis="y", alpha=0.3)
    ax.set_axisbelow(True)
    # Below the axes, so it can never sit on top of a tall bar's value label.
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.09), ncol=2, frameon=False)

    fig.tight_layout()
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path)
    plt.close(fig)
